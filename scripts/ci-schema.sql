-- Exclusivo para CI: esquema minimo para los endpoints de solo lectura que prueba smoke-test.js.
-- No es una migracion de produccion ni sustituye el esquema completo de la aplicacion.
CREATE TABLE usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  email varchar(255) UNIQUE NOT NULL,
  password varchar(255) NOT NULL,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categorias_recetas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(150) NOT NULL
);

CREATE TABLE recetas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(150) NOT NULL,
  descripcion text,
  pais varchar(100),
  imagen_url text,
  tiempo_preparacion integer,
  porciones integer,
  dificultad varchar(50),
  usuario_id integer NOT NULL REFERENCES usuarios(id),
  categoria_id integer NOT NULL REFERENCES categorias_recetas(id),
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE comentarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receta_id integer NOT NULL REFERENCES recetas(id),
  usuario_id integer NOT NULL REFERENCES usuarios(id),
  comentario text,
  calificacion integer,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

